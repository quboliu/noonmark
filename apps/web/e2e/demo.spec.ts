import { test, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { login, navigation, snapshot } from './helpers';

test('一年演示资料：真实长列表、跨季度历史与底部速记', async ({ page }) => {
  const reportRoot = join(process.env.NOONMARK_RUN_ROOT!, 'reports');
  await mkdir(join(reportRoot, 'screenshots'), { recursive: true });
  let pageErrors = 0;
  let failedAPI = 0;
  page.on('pageerror', () => { pageErrors++; });
  page.on('response', response => { if (new URL(response.url()).pathname.startsWith('/api/') && response.status() >= 400) failedAPI++; });
  const token = await login(page);
  const before = await snapshot(page, token);
  expect(before.instance_id, '浏览器必须连接本轮已回读验收的演示实例').toBe(process.env.NOONMARK_DEMO_INSTANCE_ID);
  const current = before.traces.filter(trace => trace.date === before.today && trace.status !== 'cancelledDraft');
  const completed = before.traces.filter(trace => trace.status === 'completed');
  const totalReviews = before.days.filter(day => day.summary.length > 0);
  const historicalReviews = before.days.filter(day => day.date < before.today && day.summary.length > 0);
  const future = before.traces.filter(trace => trace.date > before.today && trace.status === 'pending');
  expect(current.length).toBeGreaterThanOrEqual(60);
  expect(completed.length).toBeGreaterThanOrEqual(365);
  expect(totalReviews.length).toBeGreaterThanOrEqual(365);
  expect(historicalReviews.length).toBeGreaterThanOrEqual(364);
  expect(future.length).toBeGreaterThanOrEqual(8);
  await expect(page.locator('.task-row')).toHaveCount(current.length);
  await page.screenshot({ path: join(reportRoot, 'screenshots', 'demo-desktop.png') });
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  expect(await page.evaluate(() => scrollY > innerHeight)).toBe(true);
  await expect(page.locator('.sidebar')).toBeInViewport();
  await page.screenshot({ path: join(reportRoot, 'screenshots', 'demo-desktop-bottom.png') });
  await page.keyboard.press('Control+k');
  const dialog = page.getByRole('dialog', { name: '添加任务', exact: true });
  const title = dialog.getByLabel('任务名称', { exact: true });
  await expect(title).toBeEnabled();
  await expect(title).toBeFocused();
  await title.fill('一年演示验收：从长页面底部记录下一步');
  await dialog.getByLabel('安排日期', { exact: true }).fill(before.today);
  await dialog.getByRole('button', { name: '添加任务', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  const after = await snapshot(page, token);
  expect(after.chains.length).toBe(before.chains.length + 1);
  expect(after.definitions.some(definition => definition.title === '一年演示验收：从长页面底部记录下一步')).toBe(true);
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.locator('.sidebar'), '移动侧栏收起后才采集页面证据').not.toBeInViewport();
  await expect(page.getByRole('heading', { name: 'Day Todo', exact: true })).toBeVisible();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: join(reportRoot, 'screenshots', 'demo-mobile.png') });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), '长页面在移动尺寸不得横向溢出').toBe(true);
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight));
  await page.screenshot({ path: join(reportRoot, 'screenshots', 'demo-mobile-bottom.png') });
  expect(await page.evaluate(() => { const ids = [...document.querySelectorAll('[id]')].map(element => element.id); return ids.length === new Set(ids).size; })).toBe(true);
  await page.evaluate(() => window.scrollTo(0, 0));
  await navigation(page, '便签');
  await expect(page.locator('.idea-list > li')).toHaveCount(before.ideas.filter(idea => idea.pinned_at && !idea.deleted_at).length);
  expect(pageErrors).toBe(0);
  expect(failedAPI).toBe(0);
  await writeFile(join(reportRoot, 'demo-browser-evidence.json'), JSON.stringify({ verdict: 'PASS', today_traces: current.length, review_days: totalReviews.length, historical_reviews: historicalReviews.length, completed_traces: completed.length, future_traces: future.length, page_errors: pageErrors, failed_api: failedAPI, long_scroll_command_committed: true, checked_viewports: 2 }) + '\n');
});
