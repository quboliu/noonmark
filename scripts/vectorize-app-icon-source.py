#!/usr/bin/env python3

"""Rebuild Noonmark's canonical AppIcon SVG from its committed PNG reference."""

from __future__ import annotations

import argparse
import colorsys
import hashlib
import html
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path


REPOSITORY_ROOT = Path(__file__).resolve().parent.parent
REFERENCE_SOURCE = (
    REPOSITORY_ROOT
    / "docs"
    / "assets"
    / "brand"
    / "noonmark-logo-reference.png"
)
REFERENCE_SHA256 = (
    "9130bd34e01eb56c5637f28f04acfbc2ac541bf3422467f43796b8fe93d092a3"
)
EXPECTED_CANDIDATE_PATHS = 2_867
EXPECTED_SYMBOL_PATHS = 1_645


